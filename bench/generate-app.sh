#!/usr/bin/env bash
# Generates the benchmark app: phx.new + phx.gen.auth + 40 scoped phx.gen.live
# resources in 8 contexts, routed in the authenticated live_session.
#   bench/generate-app.sh DIR
set -euo pipefail
DIR=${1:-shop}
rm -rf "$DIR"
mix phx.new "$DIR" --app shop --database sqlite3 --install >/dev/null
cd "$DIR"
rm -f AGENTS.md
mix phx.gen.auth Accounts User users --live </dev/null >/dev/null
mix deps.get >/dev/null

contexts=(Catalog Sales Support Inventory Crm Billing Events Content)
schemas=(Alpha Bravo Charlie Delta Echo)
routes=""

for context in "${contexts[@]}"; do
  for schema in "${schemas[@]}"; do
    name="${context}${schema}"
    plural=$(echo "${name}s" | sed -E 's/([a-z])([A-Z])/\1_\2/g' | tr '[:upper:]' '[:lower:]')
    mix phx.gen.live "$context" "$name" "$plural" --merge-with-existing-context \
      title:string body:text price:decimal quantity:integer active:boolean due_on:date >/dev/null
    routes+="      live \"/$plural\", ${name}Live.Index, :index"$'\n'
    routes+="      live \"/$plural/new\", ${name}Live.Form, :new"$'\n'
    routes+="      live \"/$plural/:id\", ${name}Live.Show, :show"$'\n'
    routes+="      live \"/$plural/:id/edit\", ${name}Live.Form, :edit"$'\n'
  done
done

# routes go into the authenticated live_session generated by phx.gen.auth
ROUTES="$routes" perl -0pi -e 's/(live_session :require_authenticated_user,\n.*?\] do\n)/$1$ENV{ROUTES}/s' lib/shop_web/router.ex
mix format
mix compile --warnings-as-errors >/dev/null
echo "generated $(find lib -name '*.ex' | wc -l | tr -d ' ') .ex files, $(find lib -name '*.heex' | wc -l | tr -d ' ') .heex files"
